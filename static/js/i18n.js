  // Helper to get selected language from localStorage or Cookie
  function getCurrentLanguage() {
    try {
      const stored = localStorage.getItem('freefood_lang');
      if (stored && SUPPORTED_LANGUAGES[stored]) {
        return stored;
      }
      // Check cookie
      const match = document.cookie.match(/(^|;)\s*freefood_lang\s*=\s*([^;]+)/);
      if (match && SUPPORTED_LANGUAGES[match[2]]) {
        return match[2];
      }
    } catch (e) {
      console.warn('[i18n] Error reading language preference', e);
    }
    return 'en';
  }

  // Set language preference and update UI
  function setLanguage(langCode) {
    if (!SUPPORTED_LANGUAGES[langCode]) {
      langCode = 'en';
    }

    try {
      localStorage.setItem('freefood_lang', langCode);
      const oneYear = 365 * 24 * 60 * 60;
      document.cookie = `freefood_lang=${langCode}; path=/; max-age=${oneYear}; SameSite=Lax`;
    } catch (e) {
      console.warn('[i18n] Error saving language preference', e);
    }

    document.documentElement.lang = langCode;
    updateSelectorUI(langCode);
    translateDOM(langCode);
  }

